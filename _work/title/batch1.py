LAWS = "prototype/data/laws"
ok, missing, mismatch = 0, [], []
for lid, zh in TR.items():
    p = os.path.join(LAWS, lid + ".json")
    if not os.path.isfile(p):
        missing.append(lid); continue
    o = json.load(io.open(p, encoding="utf-8"))
    t = o.get("title") or {}
    if t.get("zh"):
        mismatch.append((lid, "已有中文标题，跳过")); continue
    src = t.get("en") or ""
    t["zh"] = zh
    o["title"] = t
    o["titleTranslation"] = {
        "engine": "manual-llm", "reviewed": False, "source": src,
        "note": "人工逐条翻译（模型产出，未经人工复核）；公司名、地名、机构名保留原文。",
    }
    io.open(p, "w", encoding="utf-8").write(json.dumps(o, ensure_ascii=False, indent=1))
    ok += 1

